#!/usr/bin/env python3
"""Generate handbook/competencies.md and learner/competencies.yaml from handbook/matrix.yaml.

Learner state (state, evidence, last_exercised) already present in learner/competencies.yaml is preserved.
Usage: python3 scripts/gen-competencies.py
Requires: PyYAML (pip install pyyaml)
"""
import os
import sys

import yaml

ROOT = os.path.realpath(os.path.join(os.path.dirname(__file__), ".."))
MATRIX = os.path.join(ROOT, "handbook", "matrix.yaml")
OUT_MD = os.path.join(ROOT, "handbook", "competencies.md")
OUT_STATE = os.path.join(ROOT, "learner", "competencies.yaml")
LEVELS = ["L1", "L2", "L3", "L4"]
STATES = ["not-seen", "assisted", "independent", "teaches"]


def main() -> int:
    with open(MATRIX, encoding="utf-8") as f:
        matrix = yaml.safe_load(f)

    old = {}
    if os.path.exists(OUT_STATE):
        with open(OUT_STATE, encoding="utf-8") as f:
            old = (yaml.safe_load(f) or {}).get("subcodes", {}) or {}

    md = [
        "# Competency matrix",
        "",
        "<!-- GENERATED by scripts/gen-competencies.py from handbook/matrix.yaml. Do not edit by hand. -->",
        "",
        "Each subcode is one observable behaviour. A subcode becomes **required** at the level shown and stays required at "
        "higher levels. States: `not-seen`, `assisted`, `independent`, `teaches`. Promotion needs every required subcode "
        "at `independent` with at least 2 evidence links from at least 2 different sprints (see `docs/PROGRAM.md`).",
        "",
    ]
    subcodes = {}
    for area, spec in matrix.items():
        md.append(f"## {area}: {spec['name']}")
        md.append("")
        n = 0
        for lvl in LEVELS:
            behaviours = spec[lvl]
            if len(behaviours) < 3 or len(behaviours) > 6:
                print(f"{area} {lvl}: needs 3-6 behaviours, has {len(behaviours)}", file=sys.stderr)
                return 1
            md.append(f"**{lvl}**")
            md.append("")
            for b in behaviours:
                n += 1
                code = f"{area}.{n}"
                md.append(f"- `{code}` {b}")
                prev = old.get(code, {})
                subcodes[code] = {
                    "area": area,
                    "level": lvl,
                    "behaviour": b,
                    "state": prev.get("state", "not-seen"),
                    "evidence": prev.get("evidence", []),
                    "last_exercised": prev.get("last_exercised"),
                }
            md.append("")

    with open(OUT_MD, "w", encoding="utf-8") as f:
        f.write("\n".join(md))

    header = (
        "# Learner competency state. Machine-readable. Written by agents, validated by scripts/validate-state.\n"
        "# state: not-seen | assisted | independent | teaches\n"
        "# evidence: list of {link, sprint, date, note}\n"
    )
    with open(OUT_STATE, "w", encoding="utf-8") as f:
        f.write(header)
        yaml.safe_dump({"subcodes": subcodes}, f, sort_keys=False, width=120, allow_unicode=True)
    print(f"{len(subcodes)} subcodes across {len(matrix)} areas")
    return 0


if __name__ == "__main__":
    sys.exit(main())
